import { createHash } from "node:crypto";
import { DefaultAzureCredential } from "@azure/identity";
import type { Principal } from "./auth.js";
import { HttpError } from "./http.js";
import { CosmosSkunkieBudgetStore, budgetStorageUnavailable, type BudgetStoreDocument, type BudgetStoreRecord, type SkunkieBudgetStore } from "./skunkieBudgetStore.js";

export const SKUNKIE_MONTHLY_LIMIT_NANOS = 1_000_000_000;
export const SKUNKIE_BUDGET_MODEL = "gpt-4.1-mini" as const;
export const SKUNKIE_INPUT_NANOS_PER_TOKEN = 400;
export const SKUNKIE_OUTPUT_NANOS_PER_TOKEN = 1600;
// Bound a single Cosmos document below its 2 MB limit, including settled IDs.
// IDs are retained so a replay cannot spend or settle twice. No messages stored.
export const SKUNKIE_MAX_MONTHLY_RESERVATIONS = 4096;
const collection = "skunkie-budget-v1" as const;
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
type BudgetPrincipal = Pick<Principal, "tenantId" | "subject">;
export interface SkunkieTokenUsage { inputTokens: number; outputTokens: number }
export interface SkunkieReservationRequest {
  /** Generated by the server once for this provider attempt; never a browser identity. */
  requestId: string;
  model: typeof SKUNKIE_BUDGET_MODEL;
  maxInputTokens: number;
  maxOutputTokens: number;
}
export interface SkunkieBudgetReservation {
  accountKey: string; month: string; requestId: string;
  model: typeof SKUNKIE_BUDGET_MODEL; reservedNanos: number;
}
export interface SkunkieBudgetSnapshot {
  month: string; resetsAt: string; limitNanos: number;
  /** Includes unsettled reservations, even after provider timeout or process crash. */
  usedNanos: number; remainingNanos: number; blocked: boolean; requestLimitReached: boolean;
}
export interface SkunkieReserveResult {
  reservation: SkunkieBudgetReservation;
  /** Only the request that durably inserted this ID may call the provider. */
  mayDispatch: boolean;
  budget: SkunkieBudgetSnapshot;
}
interface ReservationRecord extends SkunkieReservationRequest {
  reservedNanos: number;
  state: "reserved" | "settled";
  usage?: SkunkieTokenUsage;
}
interface Ledger {
  version: 1; accountKey: string; month: string;
  limitNanos: typeof SKUNKIE_MONTHLY_LIMIT_NANOS;
  usedNanos: number; blocked: boolean; reservations: ReservationRecord[];
}

/** Counts cached input at full input price. Usage must come from the provider,
 * never from a browser, a character estimate, or an assistant's response text.
 */
export function skunkieTokenCostNanos(usage: SkunkieTokenUsage): number {
  if (!usage || !Number.isSafeInteger(usage.inputTokens) || usage.inputTokens < 0 || !Number.isSafeInteger(usage.outputTokens) || usage.outputTokens < 0) {
    throw new HttpError(502, "Skunkie could not verify model usage. The request allowance remains reserved.");
  }
  const cost = usage.inputTokens * SKUNKIE_INPUT_NANOS_PER_TOKEN + usage.outputTokens * SKUNKIE_OUTPUT_NANOS_PER_TOKEN;
  if (!Number.isSafeInteger(cost)) throw new HttpError(502, "Skunkie model usage exceeds the supported accounting range.");
  return cost;
}

export function skunkieBudgetAccountKey(principal: BudgetPrincipal): string {
  if (!principal.tenantId || !uuid.test(principal.tenantId) || !principal.subject || principal.subject.length > 1024) {
    throw new HttpError(401, "A verified Microsoft account is required for the Skunkie allowance.");
  }
  return createHash("sha256").update(JSON.stringify([principal.tenantId.toLowerCase(), principal.subject])).digest("hex");
}

export function skunkieBudgetMonth(now: Date): string {
  if (!Number.isFinite(now.getTime())) throw budgetStorageUnavailable();
  const parts = new Intl.DateTimeFormat("en-US", { timeZone: "Africa/Johannesburg", year: "numeric", month: "2-digit" }).formatToParts(now);
  return `${parts.find(part => part.type === "year")!.value}-${parts.find(part => part.type === "month")!.value}`;
}

function resetAt(month: string) {
  const [year, number] = month.split("-").map(Number);
  // Johannesburg is UTC+02:00 with no DST. month number is the next UTC month index.
  return new Date(Date.UTC(year, number, 1, -2)).toISOString();
}
function snapshot(ledger: Ledger): SkunkieBudgetSnapshot {
  const requestLimitReached = ledger.reservations.length >= SKUNKIE_MAX_MONTHLY_RESERVATIONS;
  return { month: ledger.month, resetsAt: resetAt(ledger.month), limitNanos: ledger.limitNanos,
    usedNanos: ledger.usedNanos, remainingNanos: ledger.blocked ? 0 : Math.max(0, ledger.limitNanos - ledger.usedNanos),
    blocked: ledger.blocked, requestLimitReached };
}
function documentId(accountKey: string, month: string) { return `${collection}:${accountKey}:${month}`; }
function emptyLedger(accountKey: string, month: string): Ledger {
  return { version: 1, accountKey, month, limitNanos: SKUNKIE_MONTHLY_LIMIT_NANOS, usedNanos: 0, blocked: false, reservations: [] };
}
function validRequest(value: SkunkieReservationRequest) {
  return value && uuid.test(value.requestId) && value.model === SKUNKIE_BUDGET_MODEL &&
    Number.isSafeInteger(value.maxInputTokens) && value.maxInputTokens >= 0 &&
    Number.isSafeInteger(value.maxOutputTokens) && value.maxOutputTokens > 0;
}
function validate(record: BudgetStoreRecord, accountKey: string, month: string, organizationId: string): Ledger {
  try {
    const doc = record.document;
    if (!record.etag || record.etag === "*" || doc.id !== documentId(accountKey, month) || doc.organizationId !== organizationId || doc.collection !== collection || doc.ttl !== -1) throw Error();
    const value = doc.value as Ledger;
    if (!value || value.version !== 1 || value.accountKey !== accountKey || value.month !== month || value.limitNanos !== SKUNKIE_MONTHLY_LIMIT_NANOS ||
        typeof value.blocked !== "boolean" || !Number.isSafeInteger(value.usedNanos) || value.usedNanos < 0 || !Array.isArray(value.reservations) || value.reservations.length > SKUNKIE_MAX_MONTHLY_RESERVATIONS) throw Error();
    const seen = new Set<string>();
    let total = 0;
    let overrun = false;
    for (const entry of value.reservations) {
      if (!validRequest(entry) || seen.has(entry.requestId) || entry.requestId !== entry.requestId.toLowerCase()) throw Error();
      seen.add(entry.requestId);
      const reserved = skunkieTokenCostNanos({ inputTokens: entry.maxInputTokens, outputTokens: entry.maxOutputTokens });
      if (reserved !== entry.reservedNanos || reserved <= 0 || reserved > SKUNKIE_MONTHLY_LIMIT_NANOS) throw Error();
      if (entry.state === "reserved" && entry.usage === undefined) total += reserved;
      else if (entry.state === "settled" && entry.usage) {
        const actual = skunkieTokenCostNanos(entry.usage);
        total += actual;
        overrun ||= actual > reserved || entry.usage.inputTokens > entry.maxInputTokens || entry.usage.outputTokens > entry.maxOutputTokens;
      } else throw Error();
    }
    if (!Number.isSafeInteger(total) || total !== value.usedNanos || ((overrun || total > value.limitNanos) && !value.blocked)) throw Error();
    return structuredClone(value);
  } catch { throw budgetStorageUnavailable(); }
}

export class SkunkieBudgetService {
  constructor(private readonly store: SkunkieBudgetStore, private readonly organizationId: string, private readonly now: () => Date = () => new Date()) {
    if (!organizationId.trim() || organizationId.length > 200) throw budgetStorageUnavailable();
  }
  private async load(accountKey: string, month: string) {
    let record: BudgetStoreRecord | null;
    try { record = await this.store.read(documentId(accountKey, month), this.organizationId); }
    catch { throw budgetStorageUnavailable(); }
    return { record, ledger: record ? validate(record, accountKey, month, this.organizationId) : emptyLedger(accountKey, month) };
  }
  private async save(ledger: Ledger, record: BudgetStoreRecord | null) {
    const document: BudgetStoreDocument = { id: documentId(ledger.accountKey, ledger.month), organizationId: this.organizationId, collection, ttl: -1, value: ledger };
    try { return record ? await this.store.replace(document, record.etag) : await this.store.create(document); }
    catch { throw budgetStorageUnavailable(); }
  }
  async read(principal: BudgetPrincipal): Promise<SkunkieBudgetSnapshot> {
    const { ledger } = await this.load(skunkieBudgetAccountKey(principal), skunkieBudgetMonth(this.now()));
    return snapshot(ledger);
  }
  async reserve(principal: BudgetPrincipal, request: SkunkieReservationRequest): Promise<SkunkieReserveResult> {
    if (!validRequest(request)) throw new HttpError(503, "Skunkie model allowance is not configured safely.");
    const accountKey = skunkieBudgetAccountKey(principal);
    const month = skunkieBudgetMonth(this.now());
    const requestId = request.requestId.toLowerCase();
    const reservedNanos = skunkieTokenCostNanos({ inputTokens: request.maxInputTokens, outputTokens: request.maxOutputTokens });
    const reservation: SkunkieBudgetReservation = { accountKey, month, requestId, model: request.model, reservedNanos };
    for (let attempt = 0; attempt < 32; attempt++) {
      const { record, ledger } = await this.load(accountKey, month);
      const existing = ledger.reservations.find(entry => entry.requestId === requestId);
      if (existing) {
        if (existing.model !== request.model || existing.maxInputTokens !== request.maxInputTokens || existing.maxOutputTokens !== request.maxOutputTokens) throw new HttpError(409, "Skunkie request allowance does not match the original request.");
        return { reservation, mayDispatch: false, budget: snapshot(ledger) };
      }
      if (ledger.blocked) throw new HttpError(503, "Skunkie allowance is paused because model usage could not be safely reconciled.");
      if (reservedNanos > ledger.limitNanos - ledger.usedNanos) throw new HttpError(429, "This request exceeds your remaining US$1 monthly Skunkie model allowance. It resets at the start of next month in South Africa.");
      if (ledger.reservations.length >= SKUNKIE_MAX_MONTHLY_RESERVATIONS) throw new HttpError(429, "The monthly Skunkie request limit has been reached. Your allowance resets next month in South Africa.");
      ledger.reservations.push({ requestId, model: request.model, maxInputTokens: request.maxInputTokens, maxOutputTokens: request.maxOutputTokens, reservedNanos, state: "reserved" });
      ledger.usedNanos += reservedNanos;
      if (await this.save(ledger, record)) return { reservation, mayDispatch: true, budget: snapshot(ledger) };
      // Retry only a definitive create collision / ETag conflict. An ambiguous
      // write is thrown immediately and must never authorize provider dispatch.
    }
    throw budgetStorageUnavailable();
  }
  async settle(principal: BudgetPrincipal, reservation: SkunkieBudgetReservation, usage: SkunkieTokenUsage): Promise<SkunkieBudgetSnapshot> {
    const accountKey = skunkieBudgetAccountKey(principal);
    if (reservation.accountKey !== accountKey || !/^\d{4}-(0[1-9]|1[0-2])$/.test(reservation.month) || !uuid.test(reservation.requestId)) throw new HttpError(403, "Skunkie allowance belongs to a different account or request.");
    const actual = skunkieTokenCostNanos(usage);
    for (let attempt = 0; attempt < 32; attempt++) {
      const { record, ledger } = await this.load(accountKey, reservation.month);
      const entry = ledger.reservations.find(item => item.requestId === reservation.requestId);
      if (!record || !entry || entry.model !== reservation.model || entry.reservedNanos !== reservation.reservedNanos) throw budgetStorageUnavailable();
      if (entry.state === "settled") {
        if (entry.usage?.inputTokens !== usage.inputTokens || entry.usage.outputTokens !== usage.outputTokens) throw new HttpError(409, "Skunkie usage has already been settled for this request.");
        return snapshot(ledger);
      }
      const total = ledger.usedNanos - entry.reservedNanos + actual;
      if (!Number.isSafeInteger(total)) throw budgetStorageUnavailable();
      ledger.usedNanos = total;
      ledger.blocked ||= actual > entry.reservedNanos || usage.inputTokens > entry.maxInputTokens || usage.outputTokens > entry.maxOutputTokens;
      entry.state = "settled";
      entry.usage = { inputTokens: usage.inputTokens, outputTokens: usage.outputTokens };
      if (await this.save(ledger, record)) return snapshot(ledger);
    }
    throw budgetStorageUnavailable();
  }
}

export function createSkunkieBudgetService(env: NodeJS.ProcessEnv = process.env): SkunkieBudgetService {
  const { LMS_COSMOS_ENDPOINT: endpoint, LMS_COSMOS_DATABASE: database, LMS_COSMOS_CONTAINER: container, LMS_HOME_ORGANIZATION_ID: organizationId } = env;
  if (!endpoint || !database || !container || !organizationId) throw budgetStorageUnavailable();
  const credential = new DefaultAzureCredential();
  return new SkunkieBudgetService(new CosmosSkunkieBudgetStore(endpoint, database, container, async () => (await credential.getToken("https://cosmos.azure.com/.default")).token), organizationId);
}
